// Helper function to calculate top N implant matches based on Euclidean distance of dimensions
export function findTopNImplantMatches(femoralWidth = 71.5, tibialWidth = 68.2, femoralAp = 58.4, tibialAp = 46.1, n = 3) {
  const matches = implantDatabase.map((implant) => {
    const dFemWidth = Math.pow(implant.femoralWidthMm - femoralWidth, 2);
    const dTibWidth = Math.pow(implant.tibialWidthMm - tibialWidth, 2);
    const dFemAp = Math.pow(implant.femoralApMm - femoralAp, 2);
    const dTibAp = Math.pow(implant.tibialApMm - tibialAp, 2);

    const distance = Math.sqrt(dFemWidth + dTibWidth + dFemAp + dTibAp);
    const fitErrorMm = parseFloat(distance.toFixed(2));
    const fitScore = parseFloat(Math.max(75, 100 - distance * 3.8).toFixed(1));

    const dFW = implant.femoralWidthMm - femoralWidth;
    const dTW = implant.tibialWidthMm - tibialWidth;

    const overhangRisk = (dFW > 1.5 || dTW > 1.5)
      ? "Moderate Overhang"
      : (dFW < -1.5 || dTW < -1.5)
      ? "Slight Underhang"
      : "Optimal Anatomical Fit";

    return {
      implant,
      fitErrorMm,
      fitScore,
      overhangRisk,
      deltas: {
        femoralWidth: parseFloat(dFW.toFixed(1)),
        tibialWidth: parseFloat(dTW.toFixed(1)),
        femoralAp: parseFloat((implant.femoralApMm - femoralAp).toFixed(1)),
        tibialAp: parseFloat((implant.tibialApMm - tibialAp).toFixed(1))
      }
    };
  });

  matches.sort((a, b) => a.fitErrorMm - b.fitErrorMm);
  return matches.slice(0, n);
}

// Helper function to calculate nearest implant match based on Euclidean distance of dimensions
export function findNearestImplantMatch(femoralWidth, tibialWidth, femoralAp, tibialAp) {
  const topMatches = findTopNImplantMatches(femoralWidth, tibialWidth, femoralAp, tibialAp, 1);
  return topMatches[0] || null;
}
